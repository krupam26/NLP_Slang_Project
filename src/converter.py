def _replace_word(text: str, slang: str, formal: str) -> str:
    """
    Replace a complete word while preserving punctuation.
    """

    # Lookarounds handle abbreviations containing punctuation (for example "bussin'").
    pattern = rf"(?<!\w){re.escape(slang)}(?!\w)"

    return re.sub(
        pattern,
        formal,
        text,
        flags=re.IGNORECASE
    )


def slang_to_formal(text: str) -> str:
    """
    Convert slang/informal text into a more formal form.
    """

    text = normalize_text(text)

    # Longer expressions first
    replacements = sorted(
        SLANG_TO_FORMAL.items(),
        key=lambda item: len(item[0]),
        reverse=True
    )

    result = text

    for slang, formal in replacements:
        result = _replace_word(result, slang, formal)

    # Normalize spaces around any empty glosses and removed formatting.
    result = re.sub(r"\s+", " ", result)

    # Remove spaces before punctuation
    result = re.sub(r"\s+([,.!?;:])", r"\1", result)

    return result.strip()


def formal_to_slang(text: str) -> str:
    """
    Convert formal text into casual/slang text.
    """

    text = normalize_text(text)

    replacements = sorted(
        FORMAL_TO_SLANG.items(),
        key=lambda item: len(item[0]),
        reverse=True
    )
    # Match all phrases against the original text in one pass. Sequential
    # substitutions can rewrite text inserted by an earlier replacement and
    # can miss phrases containing punctuation or apostrophes.
    alternatives = "|".join(re.escape(formal) for formal, _ in replacements)
    slang_by_formal = {formal.casefold(): slang for formal, slang in replacements}
    pattern = re.compile(rf"(?<!\w)(?:{alternatives})(?!\w)", re.IGNORECASE)
    return pattern.sub(lambda match: slang_by_formal[match.group(0).casefold()], text).strip()
